#!/usr/bin/env python3
"""
gen_github_actions.py — Generate GitHub Actions workflows for email dispatch + stats.

Produces:
  .github/workflows/email-dispatch.yml  — daily at confirmed IST time (from campaign configs)
  .github/workflows/email-stats.yml     — daily at 02:00 IST (20:30 UTC)

Usage:
  python3 gen_github_actions.py             # generate both workflows
  python3 gen_github_actions.py --dry-run   # print to stdout, don't write
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime
from pathlib import Path

SCRIPT_DIR = Path(__file__).parent
PROJECT_ROOT = SCRIPT_DIR.parent.parent.parent
EMAIL_MARKETING = PROJECT_ROOT / "email-marketing"
WORKFLOWS_DIR = PROJECT_ROOT / ".github" / "workflows"


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Generate email GH Actions workflows.")
    p.add_argument("--dry-run", action="store_true", help="Print to stdout, don't write files")
    return p.parse_args()


def ist_to_utc_cron(time_ist: str) -> str:
    """Convert HH:MM IST to a cron expression in UTC (IST = UTC+5:30)."""
    h, m = map(int, time_ist.split(":"))
    total_minutes = h * 60 + m - 330  # subtract 5h30m
    if total_minutes < 0:
        total_minutes += 1440
    utc_h = total_minutes // 60
    utc_m = total_minutes % 60
    return f"{utc_m} {utc_h} * * *"


def collect_send_times() -> list[str]:
    """Collect all unique send_time_ist values across active campaigns."""
    times = set()
    campaigns_dir = EMAIL_MARKETING / "campaigns"
    if not campaigns_dir.is_dir():
        return ["10:30"]
    for config_file in campaigns_dir.glob("*/config.json"):
        try:
            config = json.loads(config_file.read_text())
            if config.get("send_time_ist") and config.get("status") not in ("Complete", "Draft"):
                times.add(config["send_time_ist"])
        except (json.JSONDecodeError, KeyError):
            pass
    return sorted(times) if times else ["10:30"]


def gen_dispatch_workflow(send_times: list[str]) -> str:
    now = datetime.now().strftime("%Y-%m-%d")
    # For each desired send time, schedule 4 cron triggers (T, T+15, T+30, T+60)
    # GH Actions crons are best-effort with delays. Dispatcher is idempotent.
    cron_lines_list = []
    for t in send_times:
        h, m = map(int, t.split(":"))
        base = h * 60 + m
        for offset in (0, 15, 30, 60):
            tot = base + offset
            tt = f"{tot // 60 % 24:02d}:{tot % 60:02d}"
            label = "primary" if offset == 0 else f"retry +{offset}m"
            cron_lines_list.append(f"    - cron: '{ist_to_utc_cron(tt)}'  # {tt} IST ({label})")
    cron_lines = "\n".join(cron_lines_list)
    return f"""# Bhookle Email Dispatch
# Auto-generated by email-outreach skill on {now}
# DO NOT EDIT MANUALLY — regenerate via gen_github_actions.py

name: Bhookle Email Dispatch

on:
  workflow_dispatch:
  schedule:
{cron_lines}

jobs:
  dispatch:
    name: Dispatch today's email batches
    runs-on: ubuntu-latest

    steps:
      - name: Check out repo
        uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '3.11'

      - name: Install dependencies
        run: pip install requests openpyxl pytz python-dotenv google-genai

      - name: Upload campaign images to Cloudinary
        env:
          CLOUDINARY_CLOUD_NAME: ${{{{ secrets.CLOUDINARY_CLOUD_NAME }}}}
          CLOUDINARY_API_KEY: ${{{{ secrets.CLOUDINARY_API_KEY }}}}
          CLOUDINARY_API_SECRET: ${{{{ secrets.CLOUDINARY_API_SECRET }}}}
        run: |
          for slug in email-marketing/campaigns/*/; do
            slug_name=$(basename "$slug")
            echo "Uploading images for: $slug_name"
            python3 _skills/email-outreach/scripts/upload_images.py "$slug_name"
          done

      - name: Dispatch batch
        env:
          RESEND_API_KEY: ${{{{ secrets.RESEND_API_KEY }}}}
          GMAIL_USER: ${{{{ secrets.GMAIL_USER }}}}
          GMAIL_APP_PASSWORD: ${{{{ secrets.GMAIL_APP_PASSWORD }}}}
          EMAIL_ADMIN_RECIPIENT: owner@example.com
        run: |
          python3 _skills/email-outreach/scripts/dispatch_batch.py

      - name: Commit logs and image URLs
        run: |
          git config user.name "github-actions[bot]"
          git config user.email "github-actions[bot]@users.noreply.github.com"
          git add email-marketing/campaigns/*/sent-log.csv \
                  email-marketing/campaigns/*/image-urls.json || true
          git diff --staged --quiet || git commit -m "chore: email dispatch log ${{{{ github.run_id }}}}"
          git push || true
"""


def gen_stats_workflow() -> str:
    now = datetime.now().strftime("%Y-%m-%d")
    return f"""# Bhookle Email Stats
# Auto-generated by email-outreach skill on {now}
# DO NOT EDIT MANUALLY — regenerate via gen_github_actions.py

name: Bhookle Email Stats

on:
  workflow_dispatch:
  schedule:
    - cron: '30 1 * * *'  # 07:00 IST daily (01:30 UTC)

jobs:
  stats:
    name: Fetch stats and update master workbook
    runs-on: ubuntu-latest

    steps:
      - name: Check out repo
        uses: actions/checkout@v4

      - name: Set up Python
        uses: actions/setup-python@v5
        with:
          python-version: '3.11'

      - name: Install dependencies
        run: pip install requests openpyxl pytz python-dotenv

      - name: Fetch stats from Resend
        env:
          RESEND_API_KEY: ${{{{ secrets.RESEND_API_KEY }}}}
        run: |
          python3 _skills/email-outreach/scripts/fetch_stats.py --days 7

      - name: Update master workbook
        run: |
          python3 _skills/email-outreach/scripts/update_master_xlsx.py

      - name: Commit results
        run: |
          git config user.name "github-actions[bot]"
          git config user.email "github-actions[bot]@users.noreply.github.com"
          git add email-marketing/campaigns/*/results.json email-marketing/campaigns-master.xlsx || true
          git diff --staged --quiet || git commit -m "chore: email stats update ${{{{ github.run_id }}}}"
          git push || true
"""


def main() -> int:
    args = parse_args()
    send_times = collect_send_times()

    dispatch_yml = gen_dispatch_workflow(send_times)
    stats_yml = gen_stats_workflow()

    if args.dry_run:
        print("=== email-dispatch.yml ===")
        print(dispatch_yml)
        print("\n=== email-stats.yml ===")
        print(stats_yml)
        return 0

    WORKFLOWS_DIR.mkdir(parents=True, exist_ok=True)

    dispatch_path = WORKFLOWS_DIR / "email-dispatch.yml"
    dispatch_path.write_text(dispatch_yml)
    print(f"Wrote: {dispatch_path}")

    stats_path = WORKFLOWS_DIR / "email-stats.yml"
    stats_path.write_text(stats_yml)
    print(f"Wrote: {stats_path}")

    print(f"\nCron schedules:")
    for t in send_times:
        print(f"  Dispatch: {t} IST ({ist_to_utc_cron(t)} UTC)")
    print(f"  Stats   : 02:00 IST (20:30 UTC)")

    print("\nNext steps:")
    print("  1. Add RESEND_API_KEY to GitHub Secrets (repo → Settings → Secrets → Actions)")
    print("  2. git add .github/workflows/email-dispatch.yml .github/workflows/email-stats.yml")
    print("  3. git commit -m 'feat: email dispatch and stats workflows'")
    print("  4. git push → GitHub Actions will handle all future sends and stats.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
